import "server-only";
import { createReadStream, promises as fs } from "node:fs";
import path from "node:path";
import { Readable } from "node:stream";
import { getStore } from "@netlify/blobs";

/**
 * File storage abstraction. Evidence code only talks to this interface, so the local-disk driver can later be
 * replaced by cloud object storage (S3, R2, Azure Blob) without touching anything else.
 */
export interface StorageProvider {
  put(key: string, data: Buffer): Promise<void>;
  /** Streams the object (optionally a byte range). Returns null when it does not exist. */
  get(key: string, range?: { start: number; end: number }): Promise<{ stream: ReadableStream<Uint8Array>; size: number } | null>;
  delete(key: string): Promise<void>;
}

/** Keys are 32 lowercase hex characters generated by the server. Anything else is rejected (no path traversal). */
export const STORAGE_KEY_PATTERN = /^[a-f0-9]{32}$/;

function assertKey(key: string): void {
  if (!STORAGE_KEY_PATTERN.test(key)) throw new Error("Invalid storage key");
}

export class LocalDiskStorage implements StorageProvider {
  constructor(private readonly root: string) {}

  private pathFor(key: string): string {
    assertKey(key);
    return path.join(this.root, key.slice(0, 2), key); // shard by prefix to keep directories small
  }

  async put(key: string, data: Buffer): Promise<void> {
    const file = this.pathFor(key);
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, data, { flag: "wx" }); // never overwrite an existing object
  }

  async get(key: string, range?: { start: number; end: number }) {
    const file = this.pathFor(key);
    let size: number;
    try {
      size = (await fs.stat(file)).size;
    } catch {
      return null;
    }
    const stream = Readable.toWeb(createReadStream(file, range)) as ReadableStream<Uint8Array>;
    return { stream, size };
  }

  async delete(key: string): Promise<void> {
    await fs.rm(this.pathFor(key), { force: true });
  }
}

/** The subset of a Netlify Blobs store this driver uses (also lets tests inject an in-memory store). */
export interface BlobStoreLike {
  set(key: string, data: ArrayBuffer, options?: { onlyIfNew?: boolean }): Promise<{ modified: boolean } | void>;
  get(key: string, options: { type: "arrayBuffer" }): Promise<ArrayBuffer | null>;
  delete(key: string): Promise<void>;
}

/**
 * Netlify Blobs driver for hosted deployments, where the function file system is temporary. Same contract and the
 * same key rules as the local driver. Objects are small (the upload limits cap them at 50 MB), so each is read whole.
 */
export class NetlifyBlobsStorage implements StorageProvider {
  constructor(private readonly store: BlobStoreLike) {}

  async put(key: string, data: Buffer): Promise<void> {
    assertKey(key);
    const buffer = data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength) as ArrayBuffer;
    const result = await this.store.set(key, buffer, { onlyIfNew: true }); // never overwrite an existing object
    if (result && result.modified === false) throw new Error("Storage object already exists");
  }

  async get(key: string, range?: { start: number; end: number }) {
    assertKey(key);
    const whole = await this.store.get(key, { type: "arrayBuffer" });
    if (!whole) return null;
    const bytes = range ? whole.slice(range.start, range.end + 1) : whole;
    return { stream: new Response(bytes).body as ReadableStream<Uint8Array>, size: whole.byteLength };
  }

  async delete(key: string): Promise<void> {
    assertKey(key);
    await this.store.delete(key);
  }
}

let instance: StorageProvider | undefined;

/**
 * Resolves the configured provider: Netlify Blobs when running on Netlify (or STORAGE_DRIVER=netlify-blobs), otherwise
 * local disk outside the public folder so files are never served statically.
 */
export function getStorage(): StorageProvider {
  if (!instance) {
    const useBlobs = process.env.STORAGE_DRIVER === "netlify-blobs" || (process.env.STORAGE_DRIVER !== "local" && process.env.NETLIFY === "true");
    if (useBlobs) {
      instance = new NetlifyBlobsStorage(getStore({ name: "evidence", consistency: "strong" }) as unknown as BlobStoreLike);
    } else {
      instance = new LocalDiskStorage(process.env.STORAGE_DIR ?? path.join(process.cwd(), "storage"));
    }
  }
  return instance;
}

/** Test hook: swap the provider (e.g. an in-memory one). */
export function setStorageForTests(provider: StorageProvider | undefined): void {
  instance = provider;
}
